import { spawnSync } from 'node:child_process';
import type { StudyData } from '@quran-grammar/core';
import { createTableStatements, POSTGRES_SCHEMA, TABLES_CHILD_FIRST } from './schema';
import { studiesToRows, TABLES_PARENT_FIRST, type ContentRows } from './rows';
import { ORDER_BY } from './sqlite';
import type { ContentVersion } from './version';

const BATCH = 200;

/** A Postgres string literal with standard_conforming_strings (the default since 9.1). */
export function literal(value: string | number | null): string {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value)) throw new Error(`Unexpected non-integer ${value}`);
    return String(value);
  }
  if (value.includes('\u0000')) throw new Error('NUL byte in text value');
  return `'${value.replaceAll("'", "''")}'`;
}

/**
 * One transaction that creates the schema if needed and replaces all study content.
 * The schema is private: it is not added to Supabase's REST-exposed schemas and grants nothing.
 */
export function buildPostgresSql(studies: readonly StudyData[], version: ContentVersion): string {
  const rows = studiesToRows(studies);
  const s = POSTGRES_SCHEMA;
  const out: string[] = [
    '-- Generated by apps/api/src/db: Quran Grammar study content (do not edit by hand).',
    "set client_encoding = 'UTF8';",
    'begin;',
    `create schema if not exists ${s};`,
    `revoke all on schema ${s} from public;`,
    ...createTableStatements('postgres').map((statement) => `${statement};`),
    `truncate ${TABLES_CHILD_FIRST.map((table) => `${s}.${table}`).join(', ')};`,
  ];
  for (const table of TABLES_PARENT_FIRST) {
    const list = rows[table] as Record<string, string | number | null>[];
    if (!list.length) continue;
    const columns = Object.keys(list[0]);
    for (let start = 0; start < list.length; start += BATCH) {
      const values = list
        .slice(start, start + BATCH)
        .map((row) => `(${columns.map((column) => literal(row[column])).join(', ')})`);
      out.push(`insert into ${s}.${table} (${columns.join(', ')}) values\n${values.join(',\n')};`);
    }
  }
  const columns = Object.keys(version) as (keyof ContentVersion)[];
  out.push(
    `insert into ${s}.content_version (id, ${columns.join(', ')}) values (1, ${columns
      .map((column) => literal(version[column]))
      .join(', ')});`,
    'commit;',
  );
  return `${out.join('\n')}\n`;
}

/** Run SQL through a psql command line such as `psql "$URL"` or an SSH + docker exec wrapper. */
export function runPsql(psql: string, sql: string, extraArgs = ''): string {
  const result = spawnSync(`${psql} -X -q -v ON_ERROR_STOP=1 ${extraArgs}`, {
    shell: true,
    input: sql,
    encoding: 'utf8',
    maxBuffer: 512 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0)
    throw new Error(`psql failed (exit ${result.status}): ${result.stderr.slice(0, 2000)}`);
  return result.stdout;
}

/** Read every table back as JSON; one query per table keeps parsing unambiguous. */
export function readPostgres(psql: string): { rows: ContentRows; version: ContentVersion } {
  const s = POSTGRES_SCHEMA;
  const query = (sql: string) => JSON.parse(runPsql(psql, sql, '-At').trim() || 'null');
  const rows = Object.fromEntries(
    (Object.keys(ORDER_BY) as (keyof ContentRows)[]).map((table) => [
      table,
      query(
        `select coalesce(jsonb_agg(to_jsonb(t) order by ${ORDER_BY[table]
          .split(', ')
          .map((column) => `t.${column}`)
          .join(', ')}), '[]'::jsonb)::text from ${s}.${table} t;`,
      ),
    ]),
  ) as unknown as ContentRows;
  const version = query(
    `select (to_jsonb(v) - 'id')::text from ${s}.content_version v where v.id = 1;`,
  ) as ContentVersion | null;
  if (!version) throw new Error('content_version row is missing');
  return { rows, version };
}
